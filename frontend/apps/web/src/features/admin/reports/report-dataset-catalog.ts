function labelizeColumn(column: string): string {
  return column.replace(/_/g, " ").replace(/\b\w/g, (char) => char.toUpperCase());
}

export function getColumnsForDataset(datasetKey: string): Array<{ key: string; label: string }> {
  const columns = ALLOWED_REPORT_COLUMNS[datasetKey] ?? [];
  return columns.map((key) => ({ key, label: labelizeColumn(key) }));
}
